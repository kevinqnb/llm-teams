#!/usr/bin/env bash
# Run an experiment config, locally or as an SGE array job (one task per shard of the sweep).
#
# Usage: experiments/submit.sh <experiment-config.yaml> [options] [-- --set key=value ...]
#
# Options:
#   --local              run in the current shell (no qsub); default is to submit to SGE
#   --dry-run            mock backend, few episodes; implies --local
#   --shards N           split the expanded sweep into N array tasks (default: one task per condition)
#   --gpus N             GPUs per task              (-l gpus=N;           env LLM_TEAMS_GPUS, default 1)
#   --gpu-type T         GPU model                  (-l gpu_type=T;       env LLM_TEAMS_GPU_TYPE, default: unset)
#   --gpu-memory M       min GPU memory in GB       (-l gpu_memory=M;     env LLM_TEAMS_GPU_MEMORY, default: unset)
#   --runtime HH:MM:SS   wall-clock limit per task  (-l h_rt=...;         env LLM_TEAMS_RUNTIME, default 12:00:00)
#   --print              print the qsub command and job script without submitting
#   -h, --help           show this help
#
# Environment (nothing cluster- or user-specific is hard-coded):
#   LLM_TEAMS_SGE_PROJECT  qsub -P project (omitted if unset)
#   LLM_TEAMS_SGE_CORES    cores per task via `-pe omp N` (default 4; set to 0 to omit)
#   LLM_TEAMS_PRELUDE      shell snippet run at the start of each job, e.g. "module load cuda"
#   LLM_TEAMS_UV_ARGS      extra args for `uv run` inside jobs (default "--extra vllm")
#   UV_CACHE_DIR, HF_HOME  exported inside jobs if set here
#   LLM_TEAMS_RESULTS_DIR  results root (default <repo>/experiments/results)
#
# Runs are resumable: re-submitting the same config continues unfinished conditions.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

usage() { sed -n '2,/^set -euo/p' "${BASH_SOURCE[0]}" | sed '$d' | sed 's/^# \{0,1\}//'; }
die() { echo "error: $*" >&2; exit 1; }

CFG=""; LOCAL=0; DRY=0; PRINT=0; SHARDS=""; EXTRA=()
GPUS="${LLM_TEAMS_GPUS:-1}"; GPU_TYPE="${LLM_TEAMS_GPU_TYPE:-}"
GPU_MEM="${LLM_TEAMS_GPU_MEMORY:-}"; RUNTIME="${LLM_TEAMS_RUNTIME:-12:00:00}"

need_val() { [[ $# -ge 2 ]] || die "option $1 needs a value"; }
while [[ $# -gt 0 ]]; do
  case "$1" in
    -h|--help) usage; exit 0 ;;
    --local) LOCAL=1; shift ;;
    --dry-run) DRY=1; LOCAL=1; shift ;;
    --print) PRINT=1; shift ;;
    --shards) need_val "$@"; SHARDS="$2"; shift 2 ;;
    --gpus) need_val "$@"; GPUS="$2"; shift 2 ;;
    --gpu-type) need_val "$@"; GPU_TYPE="$2"; shift 2 ;;
    --gpu-memory) need_val "$@"; GPU_MEM="$2"; shift 2 ;;
    --runtime) need_val "$@"; RUNTIME="$2"; shift 2 ;;
    --) shift; EXTRA=("$@"); break ;;
    -*) die "unknown option $1 (see --help)" ;;
    *) [[ -z "$CFG" ]] || die "multiple configs given"; CFG="$1"; shift ;;
  esac
done

[[ -n "$CFG" ]] || { usage; exit 2; }
[[ -f "$CFG" ]] || die "config not found: $CFG"
command -v uv >/dev/null || die "uv not found on PATH"
CFG="$(cd "$(dirname "$CFG")" && pwd)/$(basename "$CFG")"
if [[ -n "$SHARDS" ]]; then
  [[ "$SHARDS" =~ ^[1-9][0-9]*$ ]] || die "--shards must be a positive integer, got '$SHARDS'"
fi

cd "$ROOT"
uv run llm-teams validate-configs "$CFG" >&2

# ---------------------------------------------------------------- local
if [[ $LOCAL -eq 1 ]]; then
  ARGS=("$CFG")
  [[ $DRY -eq 1 ]] && ARGS+=(--dry-run)
  exec uv run llm-teams run "${ARGS[@]}" "${EXTRA[@]+"${EXTRA[@]}"}"
fi

# ---------------------------------------------------------------- SGE
COUNT="$(uv run llm-teams sweep "$CFG" --count "${EXTRA[@]+"${EXTRA[@]}"}")"
NAME="$(uv run llm-teams sweep "$CFG" --name "${EXTRA[@]+"${EXTRA[@]}"}")"
N="${SHARDS:-$COUNT}"
if [[ "$N" -gt "$COUNT" ]]; then
  echo "warning: --shards $N exceeds the $COUNT sweep conditions; using $COUNT" >&2
  N="$COUNT"
fi

RESULTS="${LLM_TEAMS_RESULTS_DIR:-$ROOT/experiments/results}/$NAME"
LOGS="$RESULTS/logs"
STAMP="$(date +%Y%m%d-%H%M%S)"
JOB_SCRIPT="$LOGS/job_$STAMP.sh"
OVERRIDES=""
[[ ${#EXTRA[@]} -eq 0 ]] || printf -v OVERRIDES '%q ' "${EXTRA[@]}"

QSUB=(qsub -terse -t "1-$N" -N "$NAME" -o "$LOGS" -e "$LOGS" -l "h_rt=$RUNTIME")
[[ -n "${LLM_TEAMS_SGE_PROJECT:-}" ]] && QSUB+=(-P "$LLM_TEAMS_SGE_PROJECT")
[[ "${LLM_TEAMS_SGE_CORES:-4}" != "0" ]] && QSUB+=(-pe omp "${LLM_TEAMS_SGE_CORES:-4}")
[[ "$GPUS" != "0" ]] && QSUB+=(-l "gpus=$GPUS")
[[ -n "$GPU_TYPE" ]] && QSUB+=(-l "gpu_type=$GPU_TYPE")
[[ -n "$GPU_MEM" ]] && QSUB+=(-l "gpu_memory=$GPU_MEM")
QSUB+=("$JOB_SCRIPT")

job_body() {
  cat <<EOF
#!/usr/bin/env bash
# Generated by experiments/submit.sh for experiment '$NAME' ($COUNT conditions, $N array tasks)
set -euo pipefail
${UV_CACHE_DIR:+export UV_CACHE_DIR=$(printf %q "$UV_CACHE_DIR")}
${HF_HOME:+export HF_HOME=$(printf %q "$HF_HOME")}
export LLM_TEAMS_RESULTS_DIR=$(printf %q "${LLM_TEAMS_RESULTS_DIR:-$ROOT/experiments/results}")
${LLM_TEAMS_PRELUDE:-}
cd $(printf %q "$ROOT")
uv run ${LLM_TEAMS_UV_ARGS---extra vllm} llm-teams run $(printf %q "$CFG") --shard \$SGE_TASK_ID/$N $OVERRIDES
EOF
}

if [[ $PRINT -eq 1 ]]; then
  printf '# qsub command\n'; printf '%q ' "${QSUB[@]}"; printf '\n\n# job script (%s)\n' "$JOB_SCRIPT"
  job_body
  exit 0
fi

command -v qsub >/dev/null || die "qsub not found on PATH (use --local, or --print to inspect the job)"
mkdir -p "$LOGS"
job_body > "$JOB_SCRIPT"
OUT="$("${QSUB[@]}")"
JOB_ID="${OUT%%.*}"   # -terse prints "<id>.<first>-<last>:<step>" for array jobs
echo "submitted job $JOB_ID ($N array tasks, $COUNT conditions) for $NAME; logs in $LOGS"

uv run python - "$RESULTS/submissions.jsonl" "$CFG" "$OVERRIDES" "$N" "$JOB_ID" \
    "$(git -C "$ROOT" rev-parse HEAD 2>/dev/null || true)" <<'PY'
import json, sys, time
path, cfg, overrides, shards, job_id, commit = sys.argv[1:7]
rec = {"timestamp": time.strftime("%Y-%m-%dT%H:%M:%S"), "config": cfg, "overrides": overrides.strip(),
       "shards": int(shards), "job_id": job_id, "git_commit": commit}
with open(path, "a") as f:
    f.write(json.dumps(rec) + "\n")
PY
